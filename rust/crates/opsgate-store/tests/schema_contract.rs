//! Schema contract (PLAN.md 4.10): a Rust-initialised database has the
//! objects of a Python-initialised one (`fixtures/schema.sql`, generated from
//! `OpsGateService.init_db`), and Rust's start on a Python database changes
//! nothing but the dedupe index Python re-creates too.

mod common;

use std::path::Path;

use opsgate_store::schema::{self, normalize_sql};
use rusqlite::Connection;
use serde_json::Map;

const SCHEMA_SQL: &str = include_str!("../../../fixtures/schema.sql");

/// `sqlite_master` rendered the way `generate.py:build_schema` renders it,
/// without the two header lines.
fn rendered(connection: &Connection) -> String {
    let mut lines: Vec<String> = SCHEMA_SQL.lines().take(2).map(str::to_owned).collect();
    assert!(lines[0].starts_with("-- Generated by rust/fixtures/generate.py"));
    for object in schema::objects(connection).unwrap() {
        lines.push(String::new());
        lines.push(format!("-- {} {}", object.kind, object.name));
        lines.push(format!("{};", object.sql.trim()));
    }
    lines.join("\n") + "\n"
}

/// Every table, row by row, as text (`quote()` keeps storage classes apart).
fn content(connection: &Connection) -> Vec<String> {
    let mut out = Vec::new();
    for table in [
        "tickets",
        "audit_events",
        "ui_session_state",
        "runner_heartbeats",
    ] {
        let mut statement = connection
            .prepare(&format!("SELECT * FROM {table} ORDER BY rowid"))
            .unwrap();
        let count = statement.column_count();
        let names: Vec<String> = statement
            .column_names()
            .iter()
            .map(|name| (*name).to_owned())
            .collect();
        let mut rows = statement.query([]).unwrap();
        while let Some(row) = rows.next().unwrap() {
            let values: Vec<String> = (0..count)
                .map(|index| {
                    format!(
                        "{}={:?}",
                        names[index],
                        row.get::<_, rusqlite::types::Value>(index).unwrap()
                    )
                })
                .collect();
            out.push(format!("{table}: {}", values.join(", ")));
        }
    }
    out
}

fn python_database(path: &Path) -> Connection {
    let connection = Connection::open(path).unwrap();
    connection.execute_batch(SCHEMA_SQL).unwrap();
    connection
        .execute_batch(
            "INSERT INTO tickets (id, source, task_ref, title, summary, execution_plan_json, \
             policy_requirements_json, context_json, payload_checksum, state, created_by, created_at, \
             max_duration_seconds) VALUES ('t-1', 'nyxmon', 'ref', 'T', 'S', '[]', '{}', '{\"x\": 0.95}', \
             'c', 'pending_approval', 'submit:nyxmon', '2026-03-07T10:00:00Z', 3600); \
             INSERT INTO audit_events (ticket_id, event_type, actor, timestamp, metadata_json) \
             VALUES ('t-1', 'ticket_created', 'submit:nyxmon', '2026-03-07T10:00:00Z', '{\"task_ref\": \"ref\"}'); \
             INSERT INTO ui_session_state VALUES ('opsgate-admin', 4, 'fingerprint', '2026-03-07T10:00:00Z'); \
             INSERT INTO runner_heartbeats VALUES ('macstudio', '2026-10-18T09:00:00Z', '2026-10-18T09:00:00Z');",
        )
        .unwrap();
    connection
}

#[test]
fn rust_schema_is_the_python_schema() {
    let directory = tempfile::tempdir().unwrap();
    let store = common::store(directory.path());
    let connection = Connection::open(store.db_path()).unwrap();
    let rust = rendered(&connection);
    // Whitespace-normalised (PLAN.md 4.10) …
    assert_eq!(normalize_sql(&rust), normalize_sql(SCHEMA_SQL));
    // … and in fact identical, because the DDL text is Python's.
    assert_eq!(rust, SCHEMA_SQL);
    let tables: Vec<String> = connection
        .prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
        .unwrap()
        .query_map([], |row| row.get(0))
        .unwrap()
        .collect::<Result<_, _>>()
        .unwrap();
    assert_eq!(
        tables,
        [
            "audit_events",
            "runner_heartbeats",
            "sqlite_sequence",
            "tickets",
            "ui_session_state"
        ]
    );
}

#[test]
fn rust_start_on_a_python_database_changes_nothing() {
    let directory = tempfile::tempdir().unwrap();
    let path = directory.path().join("opsgate.sqlite3");
    let connection = python_database(&path);
    let before_schema = schema::objects(&connection).unwrap();
    let before_content = content(&connection);
    drop(connection);

    // The approver row exists with another fingerprint: the generation is
    // bumped, exactly as Python's start with a changed password would.
    let mut options = Map::new();
    options.insert("ui_username".into(), "someone-else".into());
    let store = opsgate_store::Store::open(common::settings(&path, &options)).unwrap();
    let connection = Connection::open(store.db_path()).unwrap();
    assert_eq!(schema::objects(&connection).unwrap(), before_schema);
    let after = content(&connection);
    let added: Vec<&String> = after
        .iter()
        .filter(|row| !before_content.contains(row))
        .collect();
    assert_eq!(added.len(), 1, "{added:?}");
    assert!(added[0].starts_with("ui_session_state: username=Text(\"someone-else\")"));
    assert!(before_content.iter().all(|row| after.contains(row)));
    assert_eq!(
        store.ui_session_generation("opsgate-admin").unwrap(),
        Some(4)
    );
    assert_eq!(
        store.ui_session_generation("someone-else").unwrap(),
        Some(1)
    );
}

#[test]
fn init_is_idempotent() {
    let directory = tempfile::tempdir().unwrap();
    let first = common::store(directory.path());
    let connection = Connection::open(first.db_path()).unwrap();
    let schema_before = schema::objects(&connection).unwrap();
    first.init_db().unwrap();
    let second = common::store(directory.path());
    assert_eq!(schema::objects(&connection).unwrap(), schema_before);
    assert_eq!(
        second.ui_session_generation("opsgate-admin").unwrap(),
        Some(1)
    );
}

#[test]
fn legacy_database_gains_the_archive_columns() {
    // A database from before archiving: `tickets` without the two columns.
    let directory = tempfile::tempdir().unwrap();
    let path = directory.path().join("opsgate.sqlite3");
    let connection = Connection::open(&path).unwrap();
    let legacy = schema::INIT_SCRIPT
        .replace("result_detail TEXT,", "result_detail TEXT")
        .replace("                    archived_at TEXT,\n", "")
        .replace("                    archived_by TEXT\n", "");
    assert_ne!(legacy, schema::INIT_SCRIPT);
    connection.execute_batch(&legacy).unwrap();
    connection
        .execute_batch(
            "INSERT INTO tickets (id, source, title, summary, execution_plan_json, \
             policy_requirements_json, context_json, payload_checksum, state, created_by, created_at, \
             max_duration_seconds) VALUES ('t-1', 'nyxmon', 'T', 'S', '[]', '{}', '{}', 'c', \
             'expired', 'submit:nyxmon', '2026-03-07T10:00:00Z', 3600)",
        )
        .unwrap();
    drop(connection);

    let store = opsgate_store::Store::open(common::settings(&path, &Map::new())).unwrap();
    let ticket = store.get_ticket("t-1").unwrap();
    assert_eq!(ticket["archived_at"], serde_json::Value::Null);
    assert_eq!(ticket["is_archived"], false);
    assert_eq!(ticket["is_archivable"], true);
    let report = opsgate_store::check::check_db(&path).unwrap();
    assert!(report.is_ok(), "{report}");
    // The table text is what SQLite makes of the ALTERs; the objects match
    // otherwise.
    let connection = Connection::open(&path).unwrap();
    let objects = schema::objects(&connection).unwrap();
    let tickets = objects
        .iter()
        .find(|object| object.name == "tickets")
        .unwrap();
    assert!(
        tickets
            .sql
            .ends_with(", archived_at TEXT, archived_by TEXT)"),
        "{}",
        tickets.sql
    );
    assert_eq!(objects.len(), 8);
}

#[test]
fn open_creates_the_parent_directory_and_sets_the_pragmas() {
    let directory = tempfile::tempdir().unwrap();
    let path = directory.path().join("a").join("b").join("opsgate.sqlite3");
    let store = opsgate_store::Store::open(common::settings(&path, &Map::new())).unwrap();
    assert!(path.is_file());
    let connection = store.connect().unwrap();
    let journal_mode: String = connection
        .query_row("PRAGMA journal_mode", [], |row| row.get(0))
        .unwrap();
    let foreign_keys: i64 = connection
        .query_row("PRAGMA foreign_keys", [], |row| row.get(0))
        .unwrap();
    let busy_timeout: i64 = connection
        .query_row("PRAGMA busy_timeout", [], |row| row.get(0))
        .unwrap();
    assert_eq!(
        (journal_mode.as_str(), foreign_keys, busy_timeout),
        ("wal", 1, 5000)
    );
}

#[test]
fn open_fails_when_the_database_cannot_be_created() {
    let directory = tempfile::tempdir().unwrap();
    let blocker = directory.path().join("file");
    std::fs::write(&blocker, b"not a directory").unwrap();
    let path = blocker.join("opsgate.sqlite3");
    let error = opsgate_store::Store::open(common::settings(&path, &Map::new())).unwrap_err();
    assert!(error.service().is_none(), "{error}");
}
