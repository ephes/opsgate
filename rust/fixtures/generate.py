def _waitress_environ(headers: list[tuple[str, str]], remote_addr: str, scheme: str) -> dict[str, Any]:
    """The WSGI environ waitress builds for these header lines (header
    parsing by waitress itself: latin-1 values, repeated lines joined with
    ", ", names with "_" dropped)."""
    raw = b"GET / HTTP/1.1\r\n" + b"".join(
        name.encode("latin-1") + b": " + value.encode("latin-1") + b"\r\n" for name, value in headers
    ) + b"\r\n"
    parser = HTTPRequestParser(Adjustments())
    assert parser.received(raw) == len(raw) and parser.completed and parser.error is None
    environ: dict[str, Any] = {"REMOTE_ADDR": remote_addr, "wsgi.url_scheme": scheme,
                               "SERVER_NAME": "opsgate", "SERVER_PORT": "8711"}
    for key, value in parser.headers.items():
        if key not in ("CONTENT_LENGTH", "CONTENT_TYPE"):
            environ.setdefault("HTTP_" + key, value)
    return environ


def _served(environ: dict[str, Any], trust_proxy_headers: bool) -> dict[str, Any]:
    """The environ the Flask application code receives in production: the
    application object ``create_app`` builds (``ProxyFix(x_for=1, x_proto=1,
    x_host=1)`` around ``wsgi_app`` only with ``OPSGATE_TRUST_PROXY_HEADERS``),
    wrapped by waitress exactly as ``waitress.server`` does for
    ``serve(app, ...)`` with default adjustments (``__main__.py``): the
    proxy-header middleware with ``trusted_proxy=None`` and
    ``clear_untrusted_proxy_headers=True``, which removes the forwarded
    headers before the application sees them."""
    seen: dict[str, Any] = {}

    def capture(environ: dict[str, Any], start_response: Any) -> list[bytes]:
        seen.update(environ)
        return []

    inner: Any = ProxyFix(capture, x_for=1, x_proto=1, x_host=1) if trust_proxy_headers else capture  # type: ignore[arg-type]
    adj = Adjustments()
    assert adj.trusted_proxy or adj.clear_untrusted_proxy_headers  # waitress.server wraps the app
    served = proxy_headers_middleware(
        inner,
        trusted_proxy=adj.trusted_proxy,
        trusted_proxy_count=adj.trusted_proxy_count,
        trusted_proxy_headers=adj.trusted_proxy_headers,
        clear_untrusted=adj.clear_untrusted_proxy_headers,
        log_untrusted=adj.log_untrusted_proxy_headers,
    )
    served(environ, None)
    return seen


def build_proxy_fix() -> str:
    """``proxy_fix.json``: request header lines → client address, scheme and
    Host the application sees in production (``python -m opsgate serve``:
    waitress with default adjustments around the Flask app of
    ``create_app``), with and without ``OPSGATE_TRUST_PROXY_HEADERS``
    (PLAN.md 4.4 step 1). Waitress removes ``X-Forwarded-*`` and
    ``Forwarded`` before Werkzeug's ``ProxyFix`` runs, so the socket's view
    is kept in both cases."""
    cases = []
    for name, headers, remote_addr, scheme in PROXY_CASES:
        results = {}
        for trust in (False, True):
            seen = _served(_waitress_environ(headers, remote_addr, scheme), trust)
            results["trusted" if trust else "untrusted"] = {
                "remote_addr": seen["REMOTE_ADDR"],
                "scheme": seen["wsgi.url_scheme"],
                "host": seen.get("HTTP_HOST"),
            }
        cases.append({
            "name": name,
            "headers": [list(header) for header in headers],
            "remote_addr": remote_addr,
            "scheme": scheme,
            "result": results,
        })
    return render_json({
        "generated_by": GENERATED_BY,
        "source": "waitress.server proxy_headers_middleware (default adjustments) around"
        " werkzeug ProxyFix(x_for=1, x_proto=1, x_host=1)",
        "cases": cases,
    })


# --- S2a: canonical JSON, checksum, float repr, stored JSON, str(), time ---
#
# The corpora below are deterministic (fixed seeds, `random.Random` methods
# whose output is stable across CPython versions). Strings never contain lone
# surrogates as characters: the fixtures must stay readable by a strict JSON
# parser, so lone surrogates appear only as escape sequences inside the JSON
# *text* of an input.

# Characters for random text: ASCII printable (weighted), every character the
# ASCII-only encoder escapes specially, and non-ASCII from the BMP and beyond.
_TEXT_POOL = [chr(c) for c in range(0x20, 0x7F)] * 3 + [
    '"', "\\", "/", "\n", "\r", "\t", "\b", "\f", "\x00", "\x01", "\x1b", "\x1f", "\x7f", "\x80", "\x9f",
    "\xa0", "\xe9", "\xff", "\u0100", "\u0301", "\u03a3", "\u0416", "\u2028", "\u2029", "\u200b", "\u3000",
    "\u4e2d", "\ufeff", "\ufffd", "\uffff", "\U00010000", "\U0001d11e", "\U0001f600", "\U0001f9ea", "\U0010ffff",
    "<", ">", "&", "'",
]


def _text(rng: random.Random, max_len: int = 24) -> str:
    return "".join(rng.choice(_TEXT_POOL) for _ in range(rng.randint(0, max_len)))


def _bits_to_float(bits: int) -> float:
    return struct.unpack("<d", struct.pack("<Q", bits))[0]


def _float_to_bits(value: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", value))[0]


def _random_float(rng: random.Random) -> float:
    """A random double. Only correctly rounded operations (parsing, the four
    arithmetic operations, ``round``), never libm functions such as ``pow``
    or ``log``, whose last bit differs between macOS and Linux."""
    kind = rng.randrange(9)
    if kind == 0:
        return round(rng.uniform(0, 100), rng.randint(0, 6))
    if kind == 1:
        return rng.uniform(-1e6, 1e6)
    if kind == 2:
        return float(rng.randint(-(10**6), 10**6))
    if kind == 3:
        return float(f"1e{rng.randint(-30, 30)}") * rng.choice([1.0, -1.0, 1.5, 9.999, 0.3])
    if kind == 4:
        value = _bits_to_float(rng.getrandbits(64))
        return value if math.isfinite(value) else 0.5
    if kind == 5:
        return rng.choice([0.0, -0.0, 0.95, 3.0, 14.0, 0.1, 1e16, 1e-05, 0.0001, 9999999999999998.0, 5e-324,
                           1.7976931348623157e308, 2.2250738585072014e-308, 123456789.125])
    if kind == 6:
        return rng.random()
    if kind == 7:
        return rng.random() * float(f"1e{rng.randint(0, 6)}")
    return _bits_to_float(rng.getrandbits(52))  # subnormal or zero


def _random_int(rng: random.Random) -> int:
    kind = rng.randrange(5)
    if kind == 0:
        return rng.randint(-10, 10)
    if kind == 1:
        return rng.randint(0, 31_536_000)
    if kind == 2:
        return rng.randint(-(2**63), 2**63)
    if kind == 3:
        return rng.choice([2**53 + 1, 2**63, -(2**63) - 1, 2**64, 10**30, -(10**40)])
    return rng.getrandbits(rng.randint(64, 400)) * rng.choice([1, -1])


def _random_scalar(rng: random.Random) -> Any:
    kind = rng.randrange(6)
    if kind == 0:
        return _text(rng)
    if kind == 1:
        return _random_int(rng)
    if kind in (2, 3):
        return _random_float(rng)
    if kind == 4:
        return rng.choice([True, False])
    return None


def _random_value(rng: random.Random, depth: int) -> Any:
    if depth <= 0 or rng.random() < 0.45:
        return _random_scalar(rng)
    if rng.random() < 0.5:
        return [_random_value(rng, depth - 1) for _ in range(rng.randint(0, 4))]
    return {_text(rng, 8): _random_value(rng, depth - 1) for _ in range(rng.randint(0, 4))}


def _random_isoformat_z(rng: random.Random) -> str:
    moment = datetime(2026, 1, 1, tzinfo=UTC) + timedelta(seconds=rng.randint(-10**8, 10**8))
    return isoformat_z(moment.replace(microsecond=rng.choice([0, rng.randint(0, 999_999)])))


