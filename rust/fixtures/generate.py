def build_schema() -> str:
    """``schema.sql``: ``sqlite_master`` of a database initialised by
    ``OpsGateService.init_db`` (PLAN.md 4.10), one statement per object:
    tables, then indexes, each by name, so the file runs as one script.
    SQLite's internal objects (``sqlite_sequence``, autoindexes) are left out:
    they have no SQL of their own. The Rust schema contract test (S3a)
    compares this with a Rust-initialised database."""
    with tempfile.TemporaryDirectory() as directory:
        db_path = Path(directory) / "opsgate.sqlite3"
        OpsGateService(_settings(db_path)).init_db()
        connection = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        try:
            rows = connection.execute(
                "SELECT type, name, sql FROM sqlite_master"
                " WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\'"
                " ORDER BY type != 'table', type, name"
            ).fetchall()
        finally:
            connection.close()
    lines = [
        f"-- Generated by {GENERATED_BY} from opsgate.service.OpsGateService.init_db.",
        "-- Do not edit: run `just rs-fixtures` (rust/PLAN.md 4.10, 7.2).",
    ]
    for kind, name, sql in rows:
        lines.append("")
        lines.append(f"-- {kind} {name}")
        lines.append(f"{sql.strip()};")
    return "\n".join(lines) + "\n"


