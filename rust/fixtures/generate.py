"""Generate the shared fixtures of the Rust port from the Python code.

Python is the oracle for the contract (rust/PLAN.md section 7.2): every
fixture is produced by calling the real ``opsgate`` package on a fixed corpus.
Fixtures are never edited by hand. The Rust tests load the files with
``include_str!``; ``tests/test_rust_fixtures.py`` regenerates them in memory
and fails when a committed file differs.

Usage (from the repository root, in the project's uv environment)::

    uv run python rust/fixtures/generate.py          # rewrite every file
    uv run python rust/fixtures/generate.py --check  # exit 1 on drift

Each slice adds its builders to ``GENERATORS``. A builder returns the file
content as text; JSON fixtures go through ``render_json`` so their formatting
is stable. Cases where the decided Rust behaviour differs (PLAN.md section 5)
carry ``"divergence": "D-n"`` and the Rust expectation.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

from opsgate.config import OpsGateSettings, SubmitterPolicy
from opsgate.service import OpsGateService

FIXTURES_DIR = Path(__file__).resolve().parent

GENERATED_BY = "rust/fixtures/generate.py"


def render_json(content: Any) -> str:
    """The stable text of a JSON fixture (sorted keys, ASCII only)."""
    return json.dumps(content, indent=1, sort_keys=True, ensure_ascii=True) + "\n"


def _settings(db_path: Path) -> OpsGateSettings:
    """Fixed API settings for builders that need a service instance."""
    return OpsGateSettings(
        service_name="opsgate",
        bind_host="127.0.0.1",
        bind_port=8711,
        db_path=str(db_path),
        session_secret="x" * 32,
        trust_proxy_headers=False,
        session_cookie_secure=False,
        session_timeout_seconds=3600,
        ui_username="opsgate-admin",
        # Never verified by these builders; `init_db` stores only its SHA-256.
        ui_password_bcrypt="fixture-placeholder-not-a-bcrypt-hash",
        max_duration_seconds_default=3600,
        policy_floor_require_reviewer_step=False,
        runner_token="runner-token-000000000000",
        submitter_policies=(
            SubmitterPolicy(source="nyxmon", token="nyxmon-token-000000000000", require_reviewer_step_floor=False),
            SubmitterPolicy(source="operator", token="operator-token-00000000000", require_reviewer_step_floor=False),
        ),
        require_tailscale_context=True,
        allowed_cidrs=("127.0.0.1/32",),
        execution_data_dir=str(db_path.parent / "remediation"),
        disable_file_path=str(db_path.parent / "remediation" / ".disabled"),
    )


def build_schema() -> str:
    """``schema.sql``: ``sqlite_master`` of a database initialised by
    ``OpsGateService.init_db`` (PLAN.md 4.10), one statement per object:
    tables, then indexes, each by name, so the file runs as one script.
    SQLite's internal objects (``sqlite_sequence``, autoindexes) are left out:
    they have no SQL of their own. The Rust schema contract test (S3a)
    compares this with a Rust-initialised database."""
    with tempfile.TemporaryDirectory() as directory:
        db_path = Path(directory) / "opsgate.sqlite3"
        OpsGateService(_settings(db_path)).init_db()
        connection = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        try:
            rows = connection.execute(
                "SELECT type, name, sql FROM sqlite_master"
                " WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\'"
                " ORDER BY type != 'table', type, name"
            ).fetchall()
        finally:
            connection.close()
    lines = [
        f"-- Generated by {GENERATED_BY} from opsgate.service.OpsGateService.init_db.",
        "-- Do not edit: run `just rs-fixtures` (rust/PLAN.md 4.10, 7.2).",
    ]
    for kind, name, sql in rows:
        lines.append("")
        lines.append(f"-- {kind} {name}")
        lines.append(f"{sql.strip()};")
    return "\n".join(lines) + "\n"


GENERATORS: dict[str, Callable[[], str]] = {
    "schema.sql": build_schema,
}


def render(name: str) -> str:
    """The current content of fixture ``name``."""
    return GENERATORS[name]()


def check_fixtures(directory: Path | None = None) -> list[str]:
    """Return the fixture files in ``directory`` (default ``FIXTURES_DIR``)
    that are missing or differ from a fresh render, sorted by name."""
    directory = FIXTURES_DIR if directory is None else directory
    stale = []
    for name in sorted(GENERATORS):
        path = directory / name
        current = path.read_bytes() if path.exists() else None
        if current != render(name).encode("utf-8"):
            stale.append(name)
    return stale


def write_fixtures(directory: Path | None = None) -> list[Path]:
    """Write every fixture into ``directory`` (default ``FIXTURES_DIR``) and
    return the paths."""
    directory = FIXTURES_DIR if directory is None else directory
    written = []
    for name in sorted(GENERATORS):
        path = directory / name
        path.write_bytes(render(name).encode("utf-8"))
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a file is missing or stale")
    args = parser.parse_args(argv)
    if args.check:
        stale = check_fixtures()
        for name in stale:
            print(f"stale fixture: {name} (run {GENERATED_BY})", file=sys.stderr)
        return 1 if stale else 0
    for path in write_fixtures():
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
